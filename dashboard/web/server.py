"""The Nova Scout dashboard page's server (Master Ref Section 9, "Dashboard"; dashboard/README.md).

    GET /                       the page (index.html, generated by build_page.py from dashboard/design/reference.html)
    GET /api/data?niche=<k>     every number on the page, as JSON.  k = all | a niche code | codes joined by commas
    GET /healthz                "ok"

Runs as the `dashboard` service in docker-compose.yml, published on 127.0.0.1:3001 only.

WHERE THE NUMBERS COME FROM. Only from the `metrics` views of migration 033, as the read-only role
nova_dashboard (the Grafana dashboard's own role and views), over a connection of its own (pgmini.py). Nothing
here writes: the role cannot, the transaction is READ ONLY, and the only statements this file contains are the
SELECTs below -- build_dashboard.py refuses to build if one reads anything but a `metrics` view. The niche
filter has Grafana's meaning: `all` is every niche including `none`; a mailbox-wide figure (the daily cap, the
bounce rate, the brake) ignores the filter, exactly as the Grafana panels do.

The only value that is ever put into a SQL text is a niche code, and only after it has been matched against the
codes the database itself lists (metrics.niche_list), so a request cannot choose a string of its own.

One request is served at a time against the database (a lock), on one connection that is closed afterwards: the
role is limited to five connections and Grafana holds some of them.
"""
import json
import os
import re
import signal
import sys
import threading
import time
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlsplit

import pgmini

HERE = os.path.dirname(os.path.abspath(__file__))
INDEX = os.path.join(HERE, "index.html")

PORT = 3001
DB_HOST = os.environ.get("NOVASCOUT_DASHBOARD_DB_HOST", "postgres")
DB_PORT = int(os.environ.get("NOVASCOUT_DASHBOARD_DB_PORT", "5432"))
DB_NAME = "novascout"
DB_USER = "nova_dashboard"
DB_PASSWORD_ENV = "NOVASCOUT_DASHBOARD_DB_PASSWORD"

LATEST_N = 5            # replies listed on the page (the Grafana panel lists 20)

# Hosts the page may be reached as. A page on another site that makes the browser resolve its own name to
# 127.0.0.1 (DNS rebinding) arrives with that other name in Host and is refused.
ALLOWED_HOSTS = {"127.0.0.1:%d" % PORT, "localhost:%d" % PORT, "[::1]:%d" % PORT}

# The page may talk to this origin and nothing else: no scripts, images, frames or requests from anywhere.
CSP = ("default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src data:; img-src data:; "
       "connect-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'")

# ---------------------------------------------------------------------------------------------------------
# The statements. $NICHES becomes a list of validated niche codes. Each is the Grafana panel's own query
# (build_dashboard.py), summed over the selected niches.
# ---------------------------------------------------------------------------------------------------------
Q_OPTIONS = "SELECT niche, label FROM metrics.niche_list ORDER BY (niche = 'none'), niche"

Q_TODAY = ("SELECT coalesce(sum(counted_toward_cap), 0)::int AS sent, max(daily_cap) AS cap\n"
           "  FROM metrics.sends_daily\n WHERE is_today AND niche IN ($NICHES)")

Q_DAYS = ("SELECT sender_day::text AS day, niche, counted_toward_cap AS n\n"
          "  FROM metrics.sends_daily\n WHERE niche IN ($NICHES)\n ORDER BY sender_day, niche")

Q_QUEUE = ("SELECT coalesce(sum(approved_queue), 0)::int AS approved,\n"
           "       round(sum(cold_sends_in_window)::numeric / max(rate_window_days), 1) AS per_day,\n"
           "       round(sum(approved_queue) / nullif(sum(cold_sends_in_window)::numeric / max(rate_window_days), 0), 1)"
           " AS days_left\n"
           "  FROM metrics.queue_runway\n WHERE niche IN ($NICHES)")

# The mailbox's own numbers: not filtered by niche (the brake belongs to the mailbox).
Q_BRAKE = ("SELECT max(brake_rate_pct) AS pct, max(brake_bounced) AS bounces, max(brake_sends) AS sends,\n"
           "       max(brake_limit_pct) AS brake_at, max(brake_window_days) AS window_days,\n"
           "       max(brake_complaints) AS complaints, max(open_pauses) AS open_pauses,\n"
           "       max(open_pause_reasons) AS reasons\n"
           "  FROM metrics.deliverability")

Q_SPAM_EVER = ("SELECT coalesce(sum(spam_complaints_ever), 0)::int AS ever\n"
               "  FROM metrics.deliverability\n WHERE niche IN ($NICHES)")

Q_REPLIES = ("SELECT coalesce(sum(total), 0)::int AS total,\n"
             "       coalesce(sum(tagged_positive + tagged_meeting_booked), 0)::int AS positive,\n"
             "       coalesce(sum(tagged_meeting_booked), 0)::int AS meetings, coalesce(sum(untagged), 0)::int AS untagged\n"
             "  FROM metrics.replies_by_type\n WHERE type = 'reply' AND niche IN ($NICHES)")

Q_CAME = ("SELECT type, sum(last_7_days)::int AS last7, sum(total)::int AS total,\n"
          "       sum(bounce_permanent)::int AS permanent, sum(bounce_transient)::int AS delay\n"
          "  FROM metrics.replies_by_type\n WHERE niche IN ($NICHES)\n GROUP BY type, type_order ORDER BY type_order")

Q_LATEST = ("SELECT date_part('epoch', received_at) AS ts, company_name, country, niche, arm, type, outcome, subject,"
            " excerpt\n  FROM metrics.latest_replies\n WHERE niche IN ($NICHES)\n ORDER BY received_at DESC\n"
            " LIMIT %d" % LATEST_N)

Q_AB = ("SELECT niche, arm, first_touches, follow_ups, replied_leads, status\n"
        "  FROM metrics.ab_arms\n WHERE niche IN ($NICHES) AND (niche <> 'none' OR first_touches > 0)\n"
        " ORDER BY niche, arm")
Q_NEED = "SELECT max(sample_needed) AS need FROM metrics.ab_arms"

Q_FUNNEL = ("SELECT coalesce(sum(leads), 0)::int AS leads, coalesce(sum(enriched), 0)::int AS enriched,\n"
            "       coalesce(sum(scored), 0)::int AS scored, coalesce(sum(contact_found), 0)::int AS contact,\n"
            "       coalesce(sum(drafted), 0)::int AS drafted, coalesce(sum(approved), 0)::int AS approved,\n"
            "       coalesce(sum(sent), 0)::int AS sent, coalesce(sum(disqualified), 0)::int AS disqualified\n"
            "  FROM metrics.funnel\n WHERE niche IN ($NICHES)")

Q_HELD = ("SELECT hold_class AS cls, sum(held)::int AS held, sum(needs_person)::int AS needs\n"
          "  FROM metrics.held_by_reason\n WHERE niche IN ($NICHES)\n GROUP BY hold_class ORDER BY 2 DESC, 1")

STATEMENTS = (Q_OPTIONS, Q_TODAY, Q_DAYS, Q_QUEUE, Q_BRAKE, Q_SPAM_EVER, Q_REPLIES, Q_CAME, Q_LATEST, Q_AB, Q_NEED,
              Q_FUNNEL, Q_HELD)


def all_sql():
    """Every statement this server can send (build_dashboard.py holds each to the metrics views)."""
    return list(STATEMENTS)


# ---------------------------------------------------------------------------------------------------------
# The request's niche selection
# ---------------------------------------------------------------------------------------------------------
class BadRequest(Exception):
    pass


def resolve_niches(requested, listed):
    """`all` / empty -> every listed code; otherwise the named codes, each of which must be listed. In the
    database's order, without repeats."""
    if requested in (None, "", "all"):
        return list(listed)
    want = requested.split(",")
    unknown = [w for w in want if w not in listed]
    if unknown:
        raise BadRequest("unknown niche: %s" % ", ".join(repr(u[:40]) for u in unknown[:3]))
    return [k for k in listed if k in want]


def literal_list(codes):
    """SQL for `IN (...)`. Codes were matched against the database's own list; the pattern check is a second lock."""
    for c in codes:
        if not re.fullmatch(r"[a-z0-9_]+", c):
            raise BadRequest("not a niche code: %r" % c[:40])
    return ", ".join("'%s'" % c for c in codes)


# ---------------------------------------------------------------------------------------------------------
# The answer
# ---------------------------------------------------------------------------------------------------------
def build_data(conn, requested):
    conn.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY")      # one snapshot for the whole answer
    try:
        options = conn.query(Q_OPTIONS)
        selected = resolve_niches(requested, [o["niche"] for o in options])
        sel = literal_list(selected)

        def q(sql):
            return conn.query(sql.replace("$NICHES", sel))

        today = q(Q_TODAY)[0]
        days = {}
        for r in q(Q_DAYS):
            days.setdefault(r["day"], {})[r["niche"]] = r["n"]
        queue = q(Q_QUEUE)[0]
        brake = conn.query(Q_BRAKE)[0]
        ever = q(Q_SPAM_EVER)[0]["ever"]
        replies = q(Q_REPLIES)[0]
        arms = {}
        for r in q(Q_AB):
            arms.setdefault(r["niche"], {"niche": r["niche"], "reached": r["status"] == "sample reached in both arms",
                                         "arms": []})["arms"].append(
                {"a": r["arm"], "n": r["first_touches"], "fu": r["follow_ups"], "rep": r["replied_leads"]})
        need = conn.query(Q_NEED)[0]["need"]
        data = {
            "asOf": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "selected": selected,
            "options": [{"key": o["niche"], "label": o["label"]} for o in options],
            "today": {"sent": today["sent"], "cap": today["cap"]},
            "days": [{"iso": d, "n": {k: days[d].get(k, 0) for k in selected}} for d in sorted(days)],
            "queue": {"approved": queue["approved"], "perDay": queue["per_day"], "daysLeft": queue["days_left"]},
            "bounce": {"pct": brake["pct"], "bounces": brake["bounces"], "sends": brake["sends"],
                       "brakeAt": brake["brake_at"], "windowDays": brake["window_days"]},
            "brake": {"paused": brake["open_pauses"] > 0, "reasons": brake["reasons"] if brake["open_pauses"] else ""},
            "spam": {"counted": brake["complaints"], "ever": ever},
            "replies": {"total": replies["total"], "positive": replies["positive"], "meetings": replies["meetings"],
                        "untagged": replies["untagged"]},
            "came": q(Q_CAME),
            "latest": q(Q_LATEST),
            "ab": [arms[k] for k in selected if k in arms],
            "need": need,
            "funnel": q(Q_FUNNEL)[0],
            "held": q(Q_HELD),
        }
        return data
    finally:
        try:
            conn.query("ROLLBACK")
        except (pgmini.PGError, OSError):
            pass        # the connection is closed by the caller either way


_db_lock = threading.Lock()


def connect():
    password = os.environ.get(DB_PASSWORD_ENV, "")
    for attempt in (1, 2, 3):
        try:
            return pgmini.Connection(DB_HOST, DB_PORT, DB_USER, password, DB_NAME)
        except (pgmini.PGError, OSError) as e:
            too_many = isinstance(e, pgmini.PGError) and e.sqlstate == "53300"
            if attempt == 3 or not (too_many or isinstance(e, OSError)):
                raise
            time.sleep(1.5)


def fetch(requested):
    with _db_lock:
        conn = connect()
        try:
            return build_data(conn, requested)
        finally:
            conn.close()


# ---------------------------------------------------------------------------------------------------------
# HTTP
# ---------------------------------------------------------------------------------------------------------
class Handler(BaseHTTPRequestHandler):
    server_version = "NovaScoutDashboard"
    sys_version = ""

    def log_message(self, fmt, *args):
        if not self.path.startswith("/healthz"):
            sys.stdout.write("%s %s\n" % (self.log_date_time_string(), fmt % args))
            sys.stdout.flush()

    def _reply(self, code, body, ctype):
        if isinstance(body, str):
            body = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Security-Policy", CSP)
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.end_headers()
        self.wfile.write(body)

    def _json(self, code, obj):
        self._reply(code, json.dumps(obj, separators=(",", ":"), ensure_ascii=False), "application/json; charset=utf-8")

    def do_GET(self):
        try:
            if self.headers.get("Host", "") not in ALLOWED_HOSTS:
                return self._json(421, {"error": "this page is served to 127.0.0.1 and localhost only"})
            url = urlsplit(self.path)
            if url.path == "/healthz":
                return self._reply(200, "ok", "text/plain; charset=utf-8")
            if url.path == "/":
                with open(INDEX, "rb") as fh:
                    return self._reply(200, fh.read(), "text/html; charset=utf-8")
            if url.path == "/api/data":
                query = parse_qs(url.query)
                if set(query) - {"niche"} or len(query.get("niche", [])) > 1:
                    return self._json(400, {"error": "the only parameter is niche"})
                try:
                    return self._json(200, fetch(query.get("niche", ["all"])[0]))
                except BadRequest as e:
                    return self._json(400, {"error": str(e)})
                except (pgmini.PGError, OSError) as e:
                    sys.stderr.write("database error: %s\n" % e)
                    sys.stderr.flush()
                    return self._json(502, {"error": "the database did not answer"})
            return self._json(404, {"error": "not found"})
        except (BrokenPipeError, ConnectionResetError):
            pass

    def do_POST(self):
        self._json(405, {"error": "read-only"})

    do_PUT = do_PATCH = do_DELETE = do_POST


def main():
    if not os.environ.get(DB_PASSWORD_ENV):
        sys.exit("%s is not set" % DB_PASSWORD_ENV)
    httpd = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    httpd.daemon_threads = True
    signal.signal(signal.SIGTERM, lambda *_: threading.Thread(target=httpd.shutdown).start())
    print("dashboard page on :%d, reading as %s from %s:%d/%s" % (PORT, DB_USER, DB_HOST, DB_PORT, DB_NAME), flush=True)
    httpd.serve_forever()


if __name__ == "__main__":
    main()
