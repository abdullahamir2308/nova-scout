"""Build the dashboard page, dashboard/web/index.html, from the design reference.

    python dashboard/web/build_page.py

The reference (dashboard/design/reference.html) is the source of truth for how the page looks and moves, so
nothing of it is retyped here: the build copies out of it, and refuses when it cannot find what it copies.

  * the whole <style> block -- the embedded fonts and every CSS rule -- verbatim, followed by a few clearly
    marked additions (the states the reference never draws: send brake paused, data service offline);
  * the brand mark, verbatim;
  * from the reference's script: the helpers ($, fmt, esc), ringSVG(), gaugeSVG() and tick(), verbatim.
    Everything else in the page's script (web/app.js) is the reference's render code with the sample DATA
    replaced by the live /api/data answer.

Generated, not hand-edited: change app.js or this file, rebuild, commit both. test_drift_guards.py checks that
the committed index.html is this build's output and that the CSS is still the reference's.
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
REFERENCE = os.path.join(ROOT, "dashboard", "design", "reference.html")
APP_JS = os.path.join(HERE, "app.js")
OUT = os.path.join(HERE, "index.html")

# What the reference does not draw but live data needs. Appended after the reference's CSS, so every reference
# rule is untouched; test_drift_guards.py holds the reference CSS to be a strict prefix.
ADDITIONS_MARK = "/* ---- additions to the reference (dashboard/web/build_page.py): states it does not draw ---- */"
ADDITIONS = """
.status.crit{border-color:rgba(255,92,112,.5); background:rgba(255,92,112,.08)}
.status.crit strong{color:var(--crit)}
.live.stale i{background:var(--warn); animation:none}
.empty{color:var(--mute)}
"""

# (name in app.js -> the pattern that finds it in the reference's script)
VERBATIM = {
    "helpers": [r"^const \$ = [^\n]*$", r"^const fmt = [^\n]*$", r"^const esc = [^\n]*$"],
    "ringSVG": [r"^function ringSVG\(pct\)\{.*?^\}$"],
    "gaugeSVG": [r"^function gaugeSVG\(\)\{.*?^\}$"],
    "tick": [r"^function tick\(\)\{[^\n]*$"],
}


def read(path):
    with io.open(path, encoding="utf-8") as fh:
        return fh.read()


def reference_parts(ref):
    style = re.search(r"<style>\n(.*?)</style>", ref, re.S)
    brand = re.search(r'<div class="brand">.*?</div>', ref, re.S)
    script = re.search(r"<script>\n(.*?)</script>", ref, re.S)      # the reference's own comment says "<script>" too
    if not (style and brand and script):
        raise AssertionError("reference.html no longer has a <style> block, a .brand block and a <script> block "
                             "where build_page.py looks for them")
    return style.group(1), brand.group(0), script.group(1)


def verbatim(script, name):
    parts = []
    for pattern in VERBATIM[name]:
        found = re.findall(pattern, script, re.M | re.S)
        if len(found) != 1:
            raise AssertionError("the reference's script has %d matches for %s (%s), expected exactly one"
                                 % (len(found), name, pattern))
        parts.append(found[0])
    return "\n".join(parts)


def build():
    ref = read(REFERENCE)
    css, brand, script = reference_parts(ref)
    app = read(APP_JS)
    for name in VERBATIM:
        mark = "/*@verbatim %s*/" % name
        if app.count(mark) != 1:
            raise AssertionError("app.js must carry %s exactly once" % mark)
        app = app.replace(mark, verbatim(script, name))
    if "/*@verbatim" in app:
        raise AssertionError("app.js names a verbatim piece build_page.py does not know")
    if "</script" in app.lower():
        raise AssertionError("app.js would end the script block early")
    return """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Nova Scout</title>
<link rel="icon" href="data:,">
<!--
  Nova Scout dashboard page. GENERATED by dashboard/web/build_page.py -- edit app.js or the build, not this file.
  The look is dashboard/design/reference.html's (its CSS, fonts and drawing functions are copied verbatim);
  the numbers come from /api/data, served by dashboard/web/server.py from the read-only metric views.
  No request leaves this origin: the server's Content-Security-Policy forbids it.
-->
<style>
%s%s%s</style>
</head>
<body>
<div class="wrap">
  <header>
    %s
    <div class="seg" id="seg" role="group" aria-label="Niche"></div>
    <div class="live" id="live"><i></i><span id="fresh">Live</span><b id="clock">--:--</b></div>
  </header>

  <main id="app" class="grid"></main>
</div>
<div class="tip" id="tip" role="tooltip"></div>

<script>
%s</script>
</body>
</html>
""" % (css, ADDITIONS_MARK, ADDITIONS, brand, app)


if __name__ == "__main__":
    page = build()
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(page)
    print("wrote %s (%d bytes): reference CSS and fonts verbatim, %d verbatim functions" %
          (os.path.relpath(OUT, ROOT), len(page.encode("utf-8")), len(VERBATIM)))
    sys.exit(0)
